"""## 6. Tokenización para Longformer

> **Diferencia clave respecto al template original:**  
> Longformer procesa el documento completo (hasta 4096 tokens) sin sliding window.  
> Se agrega `global_attention_mask` con valor 1 en el token [CLS] (posición 0) para que el modelo
> aplique atención global desde esa posición — requerimiento de la arquitectura Longformer [Beltagy et al., 2020].
"""

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

def tokenize_longformer(texts, labels, doc_ids):
    """
    Tokenización para Longformer: un fragmento por documento (hasta 4096 tokens).
    Agrega global_attention_mask con 1 en CLS (posición 0), 0 en el resto.
    Documentos que excedan 4096 tokens serán truncados — se reporta cuántos.
    """
    all_data = {
        "input_ids": [],
        "attention_mask": [],
        "global_attention_mask": [],
        "labels": [],
        "doc_id": []
    }
    truncados = 0

    for text, label, doc_id in zip(texts, labels, doc_ids):
        # Verificar si el doc excede 4096 tokens (solo para registro)
        tokens_raw = tokenizer(str(text), truncation=False)["input_ids"]
        if len(tokens_raw) > MAX_LENGTH:
            truncados += 1

        enc = tokenizer(
            str(text),
            padding="max_length",
            truncation=True,
            max_length=MAX_LENGTH,
            return_tensors=None
        )

        # Global attention: 1 en CLS (posición 0), 0 en el resto
        global_att = [0] * MAX_LENGTH
        global_att[0] = 1

        all_data["input_ids"].append(enc["input_ids"])
        all_data["attention_mask"].append(enc["attention_mask"])
        all_data["global_attention_mask"].append(global_att)
        all_data["labels"].append(label)
        all_data["doc_id"].append(doc_id)

    print(f"  {len(texts)} documentos tokenizados")
    print(f"  Documentos que exceden 4096 tokens (truncados): {truncados} ({truncados/len(texts)*100:.1f}%)")
    return Dataset.from_dict(all_data)


