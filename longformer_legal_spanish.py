    print("\n✅ Entrenamiento completado")

    # ── BÚSQUEDA DE UMBRAL ÓPTIMO EN VAL ──────────────────────
    # Nota: sin sliding window, cada doc_id aparece exactamente una vez
    # por lo que aggregate_predictions es equivalente a predicción directa.
    # Se mantiene para simetría de protocolo con los experimentos anteriores.

    def aggregate_predictions(logits, doc_ids, labels, threshold=0.5):
        probs    = torch.softmax(torch.tensor(logits), dim=-1).numpy()
        doc_data = defaultdict(lambda: {"probs": [], "label": None})
        for prob, doc_id, label in zip(probs, doc_ids, labels):
            doc_data[doc_id]["probs"].append(prob)
            doc_data[doc_id]["label"] = label
        preds, true_labels = [], []
        for doc_id in sorted(doc_data.keys()):
            avg_prob = np.mean(doc_data[doc_id]["probs"], axis=0)
            preds.append(1 if avg_prob[1] >= threshold else 0)
            true_labels.append(doc_data[doc_id]["label"])
        return np.array(preds), np.array(true_labels)

    val_predictions = trainer.predict(val_dataset)

    # Rango 0.50–0.60 con incrementos de 0.005 — igual que protocolo optimizado
    thresholds = np.arange(0.50, 0.601, 0.005)
    resultados_umbral = []
    for t in thresholds:
        preds_val, true_val = aggregate_predictions(
            val_predictions.predictions,
            val_dataset["doc_id"],
            val_dataset["labels"],
            threshold=t
        )
        f1_val = f1_score(true_val, preds_val, average='macro')
        resultados_umbral.append((round(t, 3), round(f1_val, 4)))

    mejor_umbral, mejor_f1_val = max(resultados_umbral, key=lambda x: x[1])
    print(f"\nTop 5 umbrales por F1 macro en validación:")
    for t, f in sorted(resultados_umbral, key=lambda x: x[1], reverse=True)[:5]:
        print(f"  umbral={t:.3f} → F1 macro val={f:.4f}")
    print(f"\n✅ Umbral óptimo seleccionado: {mejor_umbral} (F1 val={mejor_f1_val:.4f})")

    # ── EVALUACIÓN FINAL EN TEST CON UMBRAL ÓPTIMO ────────────
    predictions = trainer.predict(test_dataset)
    y_pred, y_true = aggregate_predictions(
        predictions.predictions,
        test_dataset["doc_id"],
        test_dataset["labels"],
        threshold=mejor_umbral
    )
    mejor_epoch = trainer.state.best_model_checkpoint

