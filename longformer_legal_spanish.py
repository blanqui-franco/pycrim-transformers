if MODALIDAD == "sin_fine_tuning":
    # ── SIN FINE-TUNING ───────────────────────────────────────
    print("\n" + "=" * 60)
    print("EXPERIMENTO: SIN FINE-TUNING")
    print("=" * 60)

    model_base = AutoModel.from_pretrained(MODEL_NAME).to(device)
    model_base.eval()

    def extract_embeddings_longformer(texts, doc_ids):
        """
        Extrae embedding del token [CLS] con atención global.
        Un forward pass por documento (sin sliding window).
        """
        embeddings = []
        for i, (text, doc_id) in enumerate(zip(texts, doc_ids)):
            enc = tokenizer(
                str(text),
                return_tensors="pt",
                max_length=MAX_LENGTH,
                truncation=True,
                padding="max_length"
            ).to(device)

            # Global attention en CLS
            global_att = torch.zeros_like(enc["attention_mask"])
            global_att[0, 0] = 1

            with torch.no_grad():
                outputs = model_base(
                    input_ids=enc["input_ids"],
                    attention_mask=enc["attention_mask"],
                    global_attention_mask=global_att
                )
            # CLS token = posición 0 del last_hidden_state
            embeddings.append(outputs.last_hidden_state[:, 0, :].cpu().numpy()[0])

            if (i + 1) % 100 == 0:
                print(f"  Procesados: {i+1}/{len(texts)}")

        return np.array(embeddings)

